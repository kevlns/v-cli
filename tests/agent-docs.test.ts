import {afterEach, expect, test} from "vitest";
import fs from "node:fs"; import path from "node:path"; import os from "node:os";
import {discoverToolSkills,readRuntimeSkill,exportToolSkill} from "../src/core/skills";
const roots:string[]=[]; afterEach(()=>{ for(const root of roots.splice(0)) fs.rmSync(root,{recursive:true,force:true}); });
function fixture(){const root=fs.mkdtempSync(path.join(os.tmpdir(),"v-cli-skill-"));roots.push(root);
 const pkg=path.join(root,"pkg");fs.mkdirSync(path.join(pkg,"skills/art-workshop/scripts"),{recursive:true});
 fs.writeFileSync(path.join(pkg,"package.json"),JSON.stringify({name:"@kevlns/art-workshop",version:"1.0.0"}));
 const manifest={package:"@kevlns/art-workshop",command:"art",skills:[{id:"art-workshop",path:"skills/art-workshop/SKILL.md"}]};
 fs.writeFileSync(path.join(pkg,"v-cli.plugin.json"),JSON.stringify(manifest));
 fs.writeFileSync(path.join(pkg,"AGENTS.md"),"developer instructions only");
 fs.writeFileSync(path.join(pkg,"skills/art-workshop/SKILL.md"),"runtime instructions");
 fs.writeFileSync(path.join(pkg,"skills/art-workshop/scripts/getty.py"),"print('getty')");
 const resolvePackage=(name:string)=>name==="@kevlns/art-workshop"?path.join(pkg,"package.json"):undefined;
 return {root,pkg,manifest,resolvePackage};}
test("declarations discover runtime skills independently of development AGENTS",()=>{const f=fixture();
 expect(discoverToolSkills(f).skills.map(s=>s.id)).toEqual(["art-workshop"]);
 expect(readRuntimeSkill("art",f).content).toBe("runtime instructions");
 expect(()=>readRuntimeSkill("unity",f)).toThrow(/未声明/);
 delete (f.manifest as any).skills;fs.writeFileSync(path.join(f.pkg,"v-cli.plugin.json"),JSON.stringify(f.manifest));
 expect(discoverToolSkills(f).skills).toEqual([]);expect(discoverToolSkills(f).diagnostics.length).toBe(1);
});
test("invalid identity, traversal and duplicate skills fail before export",()=>{const f=fixture();
 f.manifest.skills[0].path="skills/../../AGENTS.md";fs.writeFileSync(path.join(f.pkg,"v-cli.plugin.json"),JSON.stringify(f.manifest));
 expect(()=>discoverToolSkills(f)).toThrow(/无效/);
 f.manifest.skills[0].path="skills/art-workshop/SKILL.md";f.manifest.skills.push({...f.manifest.skills[0]});fs.writeFileSync(path.join(f.pkg,"v-cli.plugin.json"),JSON.stringify(f.manifest));
 expect(()=>discoverToolSkills(f)).toThrow(/重复/);
});
test("external export requires explicit host/target, preserves extensions and never adds runtime state",()=>{const f=fixture();
 expect(()=>exportToolSkill("art",{...f,host:"",directory:f.root})).toThrow(/显式/);
 const dry=exportToolSkill("art",{...f,host:"codex",directory:f.root,dryRun:true});
 expect(fs.existsSync(dry.target)).toBe(false);
 exportToolSkill("art",{...f,host:"codex",directory:f.root});
 fs.writeFileSync(path.join(dry.target,"PROJECT.md"),"local");exportToolSkill("art",{...f,host:"codex",directory:f.root});
 expect(fs.readFileSync(path.join(dry.target,"PROJECT.md"),"utf8")).toBe("local");
 expect(fs.existsSync(path.join(dry.target,"runtime.json"))).toBe(false);
 expect(fs.readFileSync(path.join(dry.target,"scripts/getty.py"),"utf8")).toContain("getty");
 expect(fs.existsSync(path.join(f.root,".codex"))).toBe(false);
});
